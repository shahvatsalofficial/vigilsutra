// Generates docs/assurance/benchmark.md and benchmarks/results-summary.json from recorded data.
// Usage: node benchmarks/report.mjs <oldResultsDir(v0.1.0 rules)> <ciOutDir>
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [oldDir, ciDir] = process.argv.slice(2);
const rd = (f) => JSON.parse(readFileSync(f, "utf8"));
const lab = rd("benchmarks/labels-v0.1.0.json");
const cmp = rd("benchmarks/comparison-results.json");
const ci = join(ciDir, "vigilsutra");
const summary = rd(join(ci, "summary.json"));
const versions = readFileSync("benchmarks/versions-ci.txt", "utf8").split("\n");

const load = (dir) => {
  const m = new Map();
  const byRule = {};
  let total = 0;
  let nonTest = 0;
  for (const f of readdirSync(dir).filter((x) => x.endsWith(".json") && x !== "summary.json")) {
    const r = rd(join(dir, f));
    const repo = f.replace(".json", "");
    for (const x of r.findings) {
      m.set(`${repo}|${x.path}|${x.startLine}|${x.ruleId}`, x);
      byRule[x.ruleId] = (byRule[x.ruleId] ?? 0) + 1;
      total++;
      if (!x.pathContext) nonTest++;
    }
  }
  return { m, byRule, total, nonTest };
};
const before = load(oldDir);
const after = load(ci);

const per = {};
for (const [k, v] of Object.entries(lab.labels)) {
  const p = (per[v.rule] ??= { n: 0, TP: 0, TT: 0, FP: 0, keptTP: 0, keptTT: 0, keptFP: 0, lowTT: 0 });
  p.n++;
  p[v.label]++;
  const f = after.m.get(k);
  if (f) {
    p["kept" + v.label]++;
    if (v.label === "TT" && f.confidence === "low") p.lowTT++;
  }
}
const tot = Object.values(per).reduce((a, p) => {
  for (const k of Object.keys(p)) a[k] = (a[k] ?? 0) + p[k];
  return a;
}, {});
const pct = (a, b) => (b ? Math.round((a / b) * 100) + "%" : "n/a");
const rules = [...new Set([...Object.keys(before.byRule), ...Object.keys(after.byRule)])].sort();
const dj = summary.repos.find((r) => r.name === "django/django");
const stillReported = tot.keptTP + tot.keptTT + tot.keptFP;
const lost = Object.entries(lab.labels).filter(([k, v]) => v.label === "TP" && !after.m.has(k)).map(([k]) => k);

const o = [];
o.push("# Real-world benchmark", "");
o.push("> Generated by `node benchmarks/report.mjs`. Raw data is in `benchmarks/` (labels, comparison, versions). Re-run with `node benchmarks/run.mjs` or the manual **benchmark** workflow.", "");
o.push("## What was measured", "");
o.push(
  `VigilSutra was run on **${summary.repos.length} public repositories** (shallow clones at the commits below, read-only, nothing executed): 7 deliberately vulnerable projects and 11 mainstream projects. The first run used the released rules (v0.1.0). A sample of **${tot.n} findings** was labeled, the false positives were studied, the rules were fixed, and the same commits were scanned again to check that real findings were kept.`,
  ""
);
o.push("### Labeling rubric", "", "| Label | Meaning |", "|---|---|");
o.push("| TP | reviewing it would plausibly reveal a real weakness in the project's own code or configuration |");
o.push("| TT | the construct is real but only in tests, fixtures, test data, archived examples or vendored/minified code |");
o.push("| FP | the rule misread the code, or the construct is not a security issue in context |", "");
o.push("> **Warning:** labels were assigned by the maintainer's AI assistant, not by an independent human reviewer. They are an honest first pass and are published in `benchmarks/labels-v0.1.0.json` so anyone can disagree and re-label. One label was already corrected during the regression check (an egress rule first read as ingress).", "");
o.push("### Sampling", "");
o.push("Up to 8 findings per rule, spread round-robin across repositories in fingerprint order (deterministic, **not random**). High-volume rules are therefore under-represented, and the numbers below are **not** population estimates or confidence intervals.", "");

o.push("## Repositories", "", "| Repository | Kind | Commit | Files | Size (MiB) | Scan time on CI (ms) | Findings now |", "|---|---|---|---|---|---|---|");
for (const r of summary.repos) o.push(`| ${r.name} | ${r.kind} | \`${r.commit.slice(0, 7)}\` | ${r.files} | ${r.mib} | ${r.ms} | ${r.total} |`);
o.push("", `Timing is from a GitHub-hosted Ubuntu runner. The largest repository (django, ${dj.files} files) took ${dj.ms} ms. No crash, hang or truncation occurred on any repository.`, "");

o.push("## Results", "", "| | v0.1.0 rules | After fixes |", "|---|---|---|");
o.push(`| Total findings on the 18 repos | ${before.total} | ${after.total} |`);
o.push(`| Findings outside test, example and vendored paths | not tracked | ${after.nonTest} |`);
o.push(`| Findings in test, example and vendored paths (confidence lowered) | not tracked | ${after.total - after.nonTest} |`, "");
o.push("### Labeled sample", "", "| | v0.1.0 | After fixes |", "|---|---|---|");
o.push(`| Labeled findings | ${tot.n} | ${stillReported} still reported |`);
o.push(`| True positives (TP) | ${tot.TP} (${pct(tot.TP, tot.n)}) | ${tot.keptTP} kept |`);
o.push(`| Test or example context (TT) | ${tot.TT} (${pct(tot.TT, tot.n)}) | ${tot.keptTT} kept, ${tot.lowTT} of them now low confidence |`);
o.push(`| False positives (FP) | ${tot.FP} (${pct(tot.FP, tot.n)}) | ${tot.keptFP} remain (${pct(tot.keptFP, stillReported)} of the sample) |`, "");
o.push(`In this sample the false-positive share fell from **${pct(tot.FP, tot.n)}** to **${pct(tot.keptFP, stillReported)}**, and ${lost.length} labeled true positive(s) were lost (below). The remaining false positives are non-security uses of MD5 or SHA-1 that a pattern cannot tell apart.`, "");
o.push("### Per rule (labeled sample)", "", "| Rule | Findings v0.1.0 | Findings now | Labeled | TP | TT | FP | FP remaining |", "|---|---|---|---|---|---|---|---|");
for (const r of rules) {
  const p = per[r];
  o.push(`| ${r} | ${before.byRule[r] ?? 0} | ${after.byRule[r] ?? 0} | ${p?.n ?? 0} | ${p?.TP ?? 0} | ${p?.TT ?? 0} | ${p?.FP ?? 0} | ${p?.keptFP ?? 0} |`);
}
o.push("", "### True positives lost by the fixes", "");
if (lost.length) for (const k of lost) o.push(`- \`${k}\`: the log call prints a decoded JWT inside a format string; the rule now only flags sensitive identifiers outside string literals. Accepted trade-off.`);
else o.push("None.");
o.push("", "## What the fixes were", "");
o.push("- Quoted local reusable workflows (`uses: './x.yml'`) were treated as third-party actions.");
o.push("- `eval(`, `innerHTML=` and `document.write(` inside string literals, and `eval` of a constant string, were reported as calls.");
o.push("- `jwt.decode(..., verify=False)` (token signature) was reported as TLS verification disabled.");
o.push("- `hashlib.sha1(..., usedforsecurity=False)`, `pickle.loads(pickle.dumps(x))` round-trips, `echo` text containing `curl | sh`, route and egress rules, wildcard `Effect: Deny` statements and `password = '$variable'` templates were reported.");
o.push("- `.env` files were reported even when they held only placeholders; a secret-named variable with a real-looking value is now required.");
o.push("- Findings under test, example, archived and vendored paths are kept but marked `pathContext: test-or-example` with low confidence.", "");
o.push("## Anecdotal known-issue spot checks (not a recall measurement)", "");
o.push("On the deliberately vulnerable repositories VigilSutra reported, among others: command injection and `eval` of request data (NodeGoat, DVNA), SQL built by string interpolation (Juice Shop code-fix snippets), `yaml.load` on request data and MD5 password hashing (Vulnerable-Flask-App), a public-read-write bucket, a wildcard custom role and a hardcoded database password (TerraGoat), privileged containers and host namespaces (Kubernetes Goat), and a committed private key (NodeGoat). These are examples that were found, **not** a list of what was missed.", "");

o.push("## Comparison with other open-source scanners", "");
o.push(`Same commits, same Linux CI run (${versions.slice(0, 2).join(", ")}). Unit: files with at least one finding, summed over the repositories.`, "");
o.push("### Secrets: VigilSutra vs Gitleaks", "", "| | Files |", "|---|---|");
o.push(`| Flagged by VigilSutra secret rules | ${cmp.totals.secrets.vigilsutra} |`, `| Flagged by Gitleaks | ${cmp.totals.secrets.gitleaks} |`, `| Both | ${cmp.totals.secrets.both} |`, `| Only VigilSutra | ${cmp.totals.secrets.onlyVigilSutra} |`, `| Only Gitleaks | ${cmp.totals.secrets.onlyGitleaks} |`, "");
o.push(`Gitleaks found things VigilSutra does not, mainly generic API keys (${cmp.gitleaksRulesVigilSutraMissed["generic-api-key"] ?? 0} files), JWTs and Kubernetes secrets, because VigilSutra has only six secret rules. VigilSutra's extra files mostly come from its broad hardcoded-credential rule (many are test files) and the \`.env\` rule. **Gitleaks is the better secrets scanner**, and it also scans git history, which VigilSutra does not. Use both.`, "");
o.push("### Code and configuration: VigilSutra vs Semgrep (`p/security-audit`)", "", "| | Files |", "|---|---|");
o.push(`| Flagged by VigilSutra (code, CI, container, IaC, agent rules) | ${cmp.totals.code.vigilsutraFiles} |`, `| Flagged by Semgrep | ${cmp.totals.code.semgrepFiles} (${cmp.totals.code.semgrepFindings} findings) |`, `| Both | ${cmp.totals.code.both} |`, `| Only VigilSutra | ${cmp.totals.code.onlyVigilSutra} |`, `| Only Semgrep | ${cmp.totals.code.onlySemgrep} |`, "");
o.push(`The overlap is small because the tools look at different things. That Semgrep ruleset is dominated by framework-specific rules (the most frequent were ${Object.keys(cmp.topSemgrepRules).slice(0, 3).join(", ")}), while VigilSutra's findings are mostly CI workflows, Dockerfiles, Kubernetes and Terraform. They complement each other; **VigilSutra does not replace Semgrep** for code analysis. Trivy and CodeQL were not compared.`, "");
o.push("## Not measured", "");
o.push("- Recall against a labeled ground truth, on any repository.");
o.push("- The false-positive rate of high-volume rules at population level (the sample is stratified, not random).");
o.push("- Independent (human) labels.");
o.push("- Comparison with Trivy or CodeQL.");
o.push("- Languages VigilSutra has no rules for (Java, Go, PHP and C# code get only secret, CI and config rules).", "");

writeFileSync("docs/assurance/benchmark.md", o.join("\n") + "\n");
writeFileSync("benchmarks/results-summary.json", JSON.stringify({ generated: new Date().toISOString(), repos: summary.repos, findingsBefore: before.total, findingsAfter: after.total, labeled: tot, perRule: per }, null, 1));
console.log("ok", JSON.stringify(tot));
